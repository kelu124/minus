#!/usr/bin/env python3
"""Intel HEX (byte-addressed, as emitted by xc-dsc-bin2hex for PIC32AK) -> C image for the RP2354 ICSP programmer.

  python3 hex2c.py <in.hex | NONE> <out.c> [name]

Records are merged into contiguous segments, padded with 0xFF to 16-byte (quadword) boundaries,
and segments whose gap is < 16 bytes are merged so no quadword is ever programmed twice (ECC rule,
DS70005583 §3.3). Only Code Flash (0x800000-0x820000) and UCA/UCB (0x7F3000-0x7F5000) are kept;
User OTP (0x7F2C00-0x7F3000) is refused because it can never be erased.
"""
import sys, os

CODE = (0x800000, 0x820000)
UCAB = (0x7F3000, 0x7F5000)
OTP  = (0x7F2C00, 0x7F3000)

def parse(path):
    mem = {}
    ext = 0
    for ln, line in enumerate(open(path), 1):
        line = line.strip()
        if not line.startswith(':'): continue
        b = bytes.fromhex(line[1:])
        n, addr, typ, data, cks = b[0], (b[1] << 8) | b[2], b[3], b[4:4 + b[0]], b[-1]
        if (sum(b) & 0xFF) != 0: sys.exit(f"{path}:{ln}: bad checksum")
        if typ == 0:
            for i, v in enumerate(data): mem[ext + addr + i] = v
        elif typ == 1: break
        elif typ == 2: ext = addr_ext = ((data[0] << 8) | data[1]) << 4
        elif typ == 4: ext = ((data[0] << 8) | data[1]) << 16
        elif typ in (3, 5): pass
        else: sys.exit(f"{path}:{ln}: unsupported record type {typ}")
    return mem

def segments(mem):
    segs = []
    for a in sorted(mem):
        if segs and a < segs[-1][0] + len(segs[-1][1]) + 16 and a >= segs[-1][0]:
            seg = segs[-1]; gap = a - (seg[0] + len(seg[1]))
            seg[1].extend([0xFF] * gap); seg[1].append(mem[a])
        else:
            segs.append([a, [mem[a]]])
    out = []
    for a, d in segs:
        start = a & ~0xF
        d = [0xFF] * (a - start) + d
        d += [0xFF] * ((-len(d)) % 16)
        out.append((start, bytes(d)))
    return out

def main():
    src, dst = sys.argv[1], sys.argv[2]
    name = sys.argv[3] if len(sys.argv) > 3 else (os.path.basename(src) if src != 'NONE' else 'none')
    segs = []
    if src != 'NONE' and os.path.exists(src):
        for a, d in segments(parse(src)):
            end = a + len(d)
            if OTP[0] <= a < OTP[1] or OTP[0] < end <= OTP[1]: sys.exit(f"refusing OTP data at 0x{a:06X}")
            if not (CODE[0] <= a and end <= CODE[1]) and not (UCAB[0] <= a and end <= UCAB[1]):
                sys.exit(f"segment 0x{a:06X}-0x{end:06X} outside Code/UCA/UCB")
            segs.append((a, d))
    with open(dst, 'w') as f:
        f.write('// generated by tools/hex2c.py — do not edit\n#include "pic_image.h"\n')
        for i, (a, d) in enumerate(segs):
            f.write(f'static const uint8_t seg{i}[{len(d)}] = {{')
            f.write(','.join(f'0x{v:02X}' for v in d)); f.write('};\n')
        f.write('const pic_segment_t pic_image_segments[] = {\n')
        for i, (a, d) in enumerate(segs): f.write(f'  {{0x{a:06X}u, {len(d)}u, seg{i}}},\n')
        f.write('  {0u, 0u, 0}\n};\n')
        f.write(f'const unsigned pic_image_nseg = {len(segs)}u;\n')
        f.write(f'const char pic_image_name[] = "{name}";\n')
        total = sum(len(d) for _, d in segs)
        f.write(f'const unsigned pic_image_bytes = {total}u;\n')
    print(f"hex2c: {len(segs)} segment(s), {sum(len(d) for _, d in segs)} bytes -> {dst}")
    for a, d in segs: print(f"  0x{a:06X} +{len(d):5d}")

if __name__ == '__main__': main()
